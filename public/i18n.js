function uiLocale() {
  return language === 'kk' ? 'kk-KZ' : 'ru-RU';
}

function translateText(value) {
  if (language !== 'kk') return value;
  const text = value.trim();
  if (translations[text]) return value.replace(text, translations[text]);
  return value
    .replace(/^(\d+) сотрудник(?:а|ов)?$/, '$1 қызметкер')
    .replace(
      /^Привет, (.*?)\. Решения и события — в одном месте\.$/,
      'Сәлем, $1. Шешімдер мен оқиғалар — бір жерде.',
    )
    .replace(
      /^Привет, (.*?)\. Заявки, развитие и поддержка — под рукой\.$/,
      'Сәлем, $1. Өтінімдер, даму және қолдау — қолжетімді.',
    )
    .replace(/^На согласовании: /, 'Келісуде: ')
    .replace(/^(\d+) дней$/, '$1 күн')
    .replace(
      /^Оформление отпуска · доступно: (\d+) дней$/,
      'Демалысты рәсімдеу · қолжетімді: $1 күн',
    )
    .replace(/^Прогресс: (\d+)%$/, 'Орындалуы: $1%')
    .replace(/^Вам повторно назначен курс «(.*?)»$/, 'Сізге «$1» курсы қайта тағайындалды');
}

function languageSwitch() {
  const russianSelected = language === 'ru';
  const kazakhSelected = language === 'kk';

  return `
    <div class="language-switch" role="group" aria-label="Language">
      <button type="button" data-language="ru" aria-pressed="${russianSelected}">RU</button>
      <button type="button" data-language="kk" aria-pressed="${kazakhSelected}">KZ</button>
    </div>
  `;
}

const originalText = new WeakMap(),
  originalAttrs = new WeakMap();
function translateUI(root = document.body) {
  document.documentElement.lang = language;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest('script,style,.bubble,.source')) continue;
    let saved = originalText.get(node);
    if (!saved || node.nodeValue !== saved.output) saved = { source: node.nodeValue };
    saved.output = translateText(saved.source);
    if (node.nodeValue !== saved.output) node.nodeValue = saved.output;
    originalText.set(node, saved);
  }
  root.querySelectorAll('[placeholder],[aria-label]').forEach((el) => {
    let saved = originalAttrs.get(el) || {};
    for (const key of ['placeholder', 'aria-label']) {
      const val = el.getAttribute(key);
      if (val !== null) {
        saved[key] ??= val;
        el.setAttribute(key, translateText(saved[key]));
      }
    }
    originalAttrs.set(el, saved);
  });
}

function bindLanguages() {
  document.querySelectorAll('[data-language]').forEach(
    (b) =>
      (b.onclick = () => {
        language = b.dataset.language;
        try {
          localStorage.setItem('jana-language', language);
        } catch {}
        document
          .querySelectorAll('[data-language]')
          .forEach((x) => x.setAttribute('aria-pressed', String(x.dataset.language === language)));
        translateUI();
        document.title = translateText(document.title.split(' · ')[0]) + ' · JanaМен';
      }),
  );
}
